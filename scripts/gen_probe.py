"""
The two evaluation contracts, generated from contracts/keepalive.py.

    python scripts/gen_probe.py           # write eval/probe_contract.py and eval/web_probe.py
    python scripts/gen_probe.py --check   # exit 1 unless both are exactly what this writes

A copy that is "the same rubric and fetch code" by intention drifts; one that
is generated cannot. Every shared function and constant is lifted out of the
contract's parsed source verbatim, and tests/test_static.py compares the parsed
trees function by function as well, so a hand edit to either file fails twice.

    eval/probe_contract.py  the judge with no money: the golden cases run
                            through it, with past windows, which a real stream
                            can never have
    eval/web_probe.py       throwaway: what each kind of page looks like to
                            validators through the exact fetch the judge uses
"""

