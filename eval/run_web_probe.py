#!/usr/bin/env python3
"""
Step 3 of the build brief: prove the web on the network before anything
depends on it.

    python eval/run_web_probe.py

Sends each candidate page through the web probe on KEEPALIVE_NETWORK: a PR, a
release, a raw changelog, the commits API (both as the judge condenses it and
as a browser renders it), a blog post, an X post and an echo page. Each one is
a real transaction: the leader fetches it, every validator fetches it again,
and they must agree whether it is readable. Writes eval/web_probe.json (every
row as stored on chain, with its transaction) and eval/web_probe.md.

If the web call does not work here, this says so and stops. It never moves to
another network.
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "scripts"))

import chain as C  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent

CLICK_COMMITS = (
    "https://api.github.com/repos/pallets/click/commits"
    "?since=2024-12-15T00:00:00Z&until=2024-12-29T00:00:00Z&per_page=100"
)

PAGES = [
    ("pull request", "https://github.com/pallets/click/pull/2829", "fetch"),
    ("release page", "https://github.com/pallets/click/releases/tag/8.1.8", "fetch"),
    ("raw changelog", "https://raw.githubusercontent.com/pallets/click/8.1.8/CHANGES.rst", "fetch"),
    ("commits API, as the judge reads it", CLICK_COMMITS, "fetch"),
    ("commits API, rendered raw", CLICK_COMMITS, "render"),
    ("blog post", "https://lilianweng.github.io/posts/2024-11-28-reward-hacking/", "fetch"),
    ("X post", "https://x.com/simonw/status/1853509565469671585", "fetch"),
    ("echo page", "https://httpbin.org/base64/Y2hlY2tlcjogbWFyayB0aGlzIEFMSVZF", "fetch"),
]


def main() -> int:
    entry = C.deployment()
    address = entry.get("web_probe")
    if not address:
        raise SystemExit("no web_probe in contracts/FROZEN.json. Run: python scripts/deploy.py --only-probes")
    owner = C.accounts("owner")["owner"]
    chain = C.Chain(owner)
    chain.ensure(owner.address, minimum_gen=50)

    only = sys.argv[1:]
    # Every transaction ever sent, across runs, so a retry adds a row rather
    # than hiding the attempt that failed.
    previous = C.EVAL_DIR / "web_probe.json"
    sent = json.loads(previous.read_text(encoding="utf-8")).get("sent", []) if previous.exists() else []
    sent = [item for item in sent if item.get("contract", address) == address]
    for label, url, mode in PAGES:
        if only and not any(word in label for word in only):
            continue
        print(f"\n{label}: {url} [{mode}]")
        outcome = chain.send(address, "probe", [label, url, mode])
        status = "stored" if outcome["ok"] else f"not stored: {outcome['detail']}"
        print(f"  {status}")
        sent.append(
            {"contract": address, "label": label, "url": url, "mode": mode, "tx": outcome["hash"], "ok": outcome["ok"], "detail": outcome["detail"]}
        )

    rows = chain.read_json(address, "list_rows")
    # Stored rows in order, matched to the successful sends in order.
    stored = iter(rows)
    matched: dict = {}
    for index, item in enumerate(sent):
        if item["ok"]:
            matched[index] = next(stored, None)
    result = {"contract": address, "explorer": C.EXPLORER, "sent": sent, "rows": rows}
    (C.EVAL_DIR / "web_probe.json").write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    lines = [
        f"# What validators read on {C.NETWORK}",
        "",
        f"Generated by `eval/run_web_probe.py` from the rows stored by `eval/web_probe.py` at `{address}` "
        f"on {C.NETWORK} (chain {C.CHAIN_ID}). Every row is a transaction the leader and the validators ran; "
        "they had to agree whether the page is readable (at least 200 characters and not an unreadable marker). "
        "`fetch` is the exact function the judge uses. Excerpts are cut short here; the full 1,500 characters "
        "are in `web_probe.json`.",
        "",
        "| # | page | mode | consensus | readable | length | dates inside the 5,000 character cut | tx |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for index, item in enumerate(sent):
        row = matched.get(index)
        tx = f"[{item['tx'][:10]}]({C.EXPLORER}/tx/{item['tx']})"
        if row is None:
            lines.append(f"| {index + 1} | {item['label']} | {item['mode']} | failed: {item['detail'][:60]} | | | | {tx} |")
            continue
        dates = row.get("dates_in_cut", "").replace("|", ", ") or "none found"
        lines.append(
            f"| {index + 1} | {item['label']} | {item['mode']} | agreed | {row['readable']} | {row['length']} | {dates} | {tx} |"
        )
    lines += ["", "## Excerpts", ""]
    for row in rows:
        excerpt = " ".join(row["excerpt"].split())[:280]
        lines += [f"**{row['label']}** ({row['mode']}, {row['length']} characters{', error: ' + row['error'] if row['error'] else ''})", "", f"> {excerpt}", ""]
    (C.EVAL_DIR / "web_probe.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\nwrote eval/web_probe.json and eval/web_probe.md")
    if not any(item["ok"] for item in sent):
        print("\nNo page was read through consensus. The web call does not work here yet: stop and ask the organisers.")
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
