"""
WebProbe - throwaway: what each kind of evidence page looks like to validators.

GENERATED by scripts/gen_probe.py from contracts/keepalive.py. Do not edit:
fetch() and commits_digest() above the class are the contract's own, lifted
verbatim, so mode "fetch" is exactly what the judge reads.

The leader's text crosses consensus and is stored: its length, a sha256 of it,
and the first 1,500 characters. Each validator fetches the same URL itself and
agrees only when its own page lands in the same readability class as the
leader's (at least 200 characters, and not an unreadable marker). A URL whose
readability differs between nodes therefore fails consensus, which is the
finding. Validators' own text never crosses, so running a URL more than once,
under rotating leaders, is how variation between nodes is seen.
"""

import datetime
import hashlib
import json
import re

from genlayer import *


E = "[EXPECTED] "

PAGE_CHARS = 5000

GITHUB_API = "https://api.github.com/repos/"

NOT_READ = "[unreadable: the page could not be fetched]"

def commits_digest(body: str) -> str:
    """
    The commits API answer as one line per commit: date, author, first line.

    The raw JSON spends two to three thousand characters on every commit, so a
    5,000 character cut would show a validator two commits out of forty. The
    same condensing runs on every node, from the same fixed response.

    The date shown is the committer date, which is the one the API filtered the
    window on. When the work was authored on a different day, that date is
    shown too, so a rebase of old work reads as what it is.
    """
    try:
        rows = json.loads(body)
    except ValueError:
        return body[:PAGE_CHARS]
    if isinstance(rows, dict):
        return ("GitHub API answered: " + str(rows.get("message", "")))[:PAGE_CHARS]
    if not isinstance(rows, list):
        return str(rows)[:PAGE_CHARS]
    if len(rows) == 0:
        return "The repository has no commits between these two dates."
    lines = [str(len(rows)) + " commits in the window, newest first:"]
    for row in rows:
        if not isinstance(row, dict):
            continue
        commit = row.get("commit") or {}
        author = commit.get("author") or {}
        committer = commit.get("committer") or {}
        authored = str(author.get("date", ""))
        committed = str(committer.get("date", "")) or authored
        message = str(commit.get("message", "")).split("\n")[0][:160]
        line = committed + " " + str(author.get("name", ""))
        if authored[:10] != committed[:10]:
            line += " (authored " + authored[:10] + ")"
        lines.append(line + ": " + message)
    return "\n".join(lines)[:PAGE_CHARS]


def fetch(url: str) -> str:
    """
    One evidence page as text, cut to 5,000 characters.

    Pages go through the web render call in text mode. The commits API is JSON,
    which is read with a plain GET and condensed, because a browser would render
    the raw JSON and the cut would keep almost none of it. A page that cannot be
    read becomes a marker the contract owns rather than an exception, so one bad
    link cannot fail a check that the other links could decide.
    """
    try:
        if url.startswith(GITHUB_API):
            response = gl.nondet.web.get(url, headers={"Accept": "application/vnd.github+json"})
            if response.status != 200 or response.body is None:
                return "[unreadable: the GitHub API answered " + str(response.status) + "]"
            return commits_digest(response.body.decode("utf-8", "replace"))
        text = gl.nondet.web.render(url, mode="text")
    except Exception:  # noqa: BLE001  any fetch failure reads as an unreadable page
        return NOT_READ
    text = str(text).strip()
    if text == "":
        return "[unreadable: the page is empty]"
    return text[:PAGE_CHARS]


MODES = ("fetch", "render", "get")
EXCERPT = 1500
#: Absolute dates as pages print them: 2024-12-19, Dec 19, 2024, 19 Dec 2024.
DATE = re.compile(
    r"\b(?:\d{4}-\d{2}-\d{2}|(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]* \d{1,2},? \d{4}"
    r"|\d{1,2} (?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]* \d{4})\b"
)


def readable(text: str) -> str:
    """The class validators must agree on, as a token rather than a bool."""
    body = text.strip()
    if len(body) < 200 or body.startswith("[unreadable"):
        return "no"
    return "yes"


def read_page(url: str, mode: str) -> dict:
    """One fetch, as a flat dict of strings."""
    error = ""
    text = ""
    try:
        if mode == "fetch":
            text = fetch(url)
        elif mode == "render":
            text = str(gl.nondet.web.render(url, mode="text"))
        else:
            response = gl.nondet.web.get(url)
            body = b"" if response.body is None else response.body
            text = "HTTP " + str(response.status) + "\n" + body.decode("utf-8", "replace")
    except Exception as failure:  # noqa: BLE001  the failure is the measurement
        error = (type(failure).__name__ + ": " + str(failure))[:300]
    return {
        "excerpt": text[:EXCERPT],
        "length": str(len(text)),
        "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        "readable": readable(text),
        "error": error,
        "dates_in_cut": "|".join(DATE.findall(text[:PAGE_CHARS])[:8]),
    }


class WebProbe(gl.Contract):
    owner: Address
    count: u64
    rows: TreeMap[str, str]

    def __init__(self):
        self.owner = gl.message.sender_address
        self.count = u64(0)

    @gl.public.write
    def probe(self, label: str, url: str, mode: str) -> None:
        if gl.message.sender_address != self.owner:
            raise gl.vm.UserError(E + "only the owner may probe")
        if mode not in MODES:
            raise gl.vm.UserError(E + "mode is fetch, render or get")
        if not url.startswith("https://") or len(url) > 300:
            raise gl.vm.UserError(E + "url must be https and at most 300 characters")
        name = label.strip()[:60]
        target = url
        how = mode

        def leader_fn():
            return read_page(target, how)

        def validator_fn(leader_result) -> bool:
            if not isinstance(leader_result, gl.vm.Return):
                return False
            theirs = leader_result.calldata
            if not isinstance(theirs, dict):
                return False
            return read_page(target, how)["readable"] == theirs.get("readable")

        out = gl.vm.run_nondet_unsafe(leader_fn, validator_fn)
        self.count = u64(int(self.count) + 1)
        row = {
            "n": int(self.count),
            "label": name,
            "url": url,
            "mode": mode,
            "at": gl.message_raw["datetime"],
            "length": int(out["length"]),
            "sha256": out["sha256"],
            "readable": out["readable"],
            "error": out["error"],
            "dates_in_cut": out["dates_in_cut"],
            "excerpt": out["excerpt"],
        }
        self.rows[str(int(self.count))] = json.dumps(row, sort_keys=True)

    @gl.public.view
    def list_rows(self) -> str:
        return json.dumps([json.loads(self.rows[str(n)]) for n in range(1, int(self.count) + 1)], sort_keys=True)
